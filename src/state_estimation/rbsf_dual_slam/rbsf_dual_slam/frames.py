"""
Frame and topic names of a SLAM implementation in the mapping slot (no ROS imports).

Exactly one component owns /map and map -> <robot>/odom (docs/DESIGN_PHILOSOPHY.md §3.2). In
DualSLAM that is the *primary* SLAM. The secondary one publishes no TF, and its map goes on
/<robot>/mapping/<impl>/map in its own frame <robot>/<impl>/map, which a static TF hangs
below `map` (identity for SLAM Toolbox, which anchors at the odometry origin; measured once by
map_overlay for Cartographer, which anchors at the start pose), so the two maps overlay.
"""

from dataclasses import dataclass

SLAM_IMPLEMENTATIONS = ('slam_toolbox', 'cartographer')


@dataclass(frozen=True)
class SlamNames:
    map_frame: str
    map_topic: str
    odom_frame: str
    base_frame: str
    publish_tf: bool


def slam_names(robot, implementation, primary):
    """Frames, map topic and TF ownership of `implementation` on car `robot`."""
    if implementation not in SLAM_IMPLEMENTATIONS:
        raise ValueError(f"Unknown SLAM '{implementation}'. Valid: {SLAM_IMPLEMENTATIONS}")
    robot = robot.strip('/')
    if primary:
        map_frame, map_topic = 'map', '/map'
    else:
        map_frame = f'{robot}/{implementation}/map'
        map_topic = f'/{robot}/mapping/{implementation}/map'
    return SlamNames(map_frame=map_frame, map_topic=map_topic, odom_frame=f'{robot}/odom',
                     base_frame=f'{robot}/base_link', publish_tf=primary)


def config_variant(platform):
    """'real' on the car, 'sim' on the simulators (docs/DESIGN_PHILOSOPHY.md §4.2)."""
    return 'real' if platform == 'real' else 'sim'


def cartographer_config(base_config, names):
    """
    Cartographer top-level Lua: `base_config` (which defines `options`) plus per-car frames.

    Cartographer reads frames from Lua only, so the launch file writes this into a temp dir.
    """
    lua_bool = 'true' if names.publish_tf else 'false'
    return (f'{base_config.rstrip()}\n\n'
            '-- Generated by rbsf_dual_slam/cartographer.launch.py\n'
            f'options.map_frame = "{names.map_frame}"\n'
            f'options.tracking_frame = "{names.base_frame}"\n'
            f'options.published_frame = "{names.odom_frame}"\n'
            f'options.odom_frame = "{names.odom_frame}"\n'
            'options.provide_odom_frame = false\n'
            'options.publish_tracked_pose = true\n'
            f'options.publish_to_tf = {lua_bool}\n'
            'return options\n')
